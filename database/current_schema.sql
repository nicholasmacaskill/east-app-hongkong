CREATE OR REPLACE FUNCTION transfer_credits(
  p_from_user_id uuid,
  p_to_user_id uuid,
  p_amount int
) RETURNS json AS $$
DECLARE
  v_from_credits int;
  v_to_credits int;
  v_parent_id uuid;
BEGIN
  IF p_amount <= 0 THEN RETURN json_build_object('success', false, 'message', 'Transfer amount must be positive'); END IF;

  SELECT credits INTO v_from_credits FROM profiles WHERE id = p_from_user_id;
  IF v_from_credits < p_amount THEN
    RETURN json_build_object('success', false, 'message', 'Insufficient credits');
  END IF;

  SELECT credits, parent_id INTO v_to_credits, v_parent_id FROM profiles WHERE id = p_to_user_id;
  
  IF v_parent_id != p_from_user_id THEN
    RETURN json_build_object('success', false, 'message', 'You can only transfer credits to your own children');
  END IF;

  UPDATE profiles SET credits = credits - p_amount WHERE id = p_from_user_id;
  UPDATE profiles SET credits = credits + p_amount WHERE id = p_to_user_id;

  RETURN json_build_object('success', true, 'message', 'Transfer successful', 'amount', p_amount);
EXCEPTION
  WHEN OTHERS THEN
    RETURN json_build_object('success', false, 'message', 'Transfer failed: ' || SQLERRM);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

