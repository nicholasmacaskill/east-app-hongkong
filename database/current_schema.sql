CREATE OR REPLACE FUNCTION cancel_session_and_refund(
  p_user_id uuid,
  p_session_id bigint
) RETURNS json AS $$
DECLARE
  v_credits_paid int;
  v_payer_id uuid;
  v_registration_id bigint;
BEGIN
  SELECT id, credits_paid, payer_id INTO v_registration_id, v_credits_paid, v_payer_id
  FROM registrations
  WHERE user_id = p_user_id AND session_id = p_session_id;

  IF v_registration_id IS NULL THEN
    RETURN json_build_object('success', false, 'message', 'Registration not found');
  END IF;

  DELETE FROM registrations WHERE id = v_registration_id;

  IF v_credits_paid > 0 THEN
    UPDATE profiles SET credits = credits + v_credits_paid WHERE id = v_payer_id;
  END IF;

  RETURN json_build_object('success', true, 'message', 'Session cancelled and refunds processed', 'refund_amount', v_credits_paid);
EXCEPTION
  WHEN OTHERS THEN
    RETURN json_build_object('success', false, 'message', 'Cancellation failed: ' || SQLERRM);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


