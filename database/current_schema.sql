CREATE OR REPLACE FUNCTION book_session_with_credits(
  p_user_id uuid,
  p_session_id bigint,
  p_attendee_id uuid DEFAULT NULL
) RETURNS json AS $$
DECLARE
  v_credits int;
  v_cost int;
  v_capacity int;
  v_count int;
  v_final_attendee_id uuid;
BEGIN
  v_final_attendee_id := COALESCE(p_attendee_id, p_user_id);

  -- Check capacity
  SELECT max_capacity, credit_cost INTO v_capacity, v_cost FROM sessions WHERE id = p_session_id;
  SELECT count(*) INTO v_count FROM registrations WHERE session_id = p_session_id;
  
  IF v_count >= v_capacity THEN
    RETURN json_build_object('success', false, 'message', 'Session is full');
  END IF;

  -- Check credits
  SELECT credits INTO v_credits FROM profiles WHERE id = p_user_id;
  IF v_credits < v_cost THEN
    RETURN json_build_object('success', false, 'message', 'Insufficient credits');
  END IF;

  -- Transact
  UPDATE profiles SET credits = credits - v_cost WHERE id = p_user_id;
  INSERT INTO registrations (user_id, session_id, payer_id, credits_paid)
  VALUES (v_final_attendee_id, p_session_id, p_user_id, v_cost);

  RETURN json_build_object('success', true, 'message', 'Booked successfully');
EXCEPTION
  WHEN OTHERS THEN
    RETURN json_build_object('success', false, 'message', 'Error: ' || SQLERRM);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


